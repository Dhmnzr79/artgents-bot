"""Refresh offline examples from canonical demo catalogs and the shared card renderer.

Run with the repository venv. No Flask app, model, dialogue or lead endpoints.
"""
from pathlib import Path
from datetime import date
import json
import re
import sys

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]
sys.path.insert(0, str(REPO))
from core.d2_tenant_snapshot import load_d2_tenant_snapshot
from core.widget_catalog import build_widget_catalog

SELECTION = [
    ('implant', 'demo', 'classic'),
    ('all-on-4', 'nikadent', 'all_on_4'),
    ('ent', 'demo_medical', 'ent_consultation'),
    ('range', 'demo_medical', 'biorevitalization'),
    ('hygiene', 'demo', 'professional_whitening'),
    ('screening', 'demo_medical', 'cervical_screening'),
    ('laser', 'demo_medical', 'laser_hair_removal'),
    ('unit', 'demo_medical', 'botulinum_therapy'),
]

def refresh():
    catalogs = {}
    for client in {client for _, client, _ in SELECTION}:
        snapshot = load_d2_tenant_snapshot(client, clients_root=REPO / 'clients')
        catalogs[client] = build_widget_catalog(snapshot, as_of=date(2026, 10, 17))
    directions, services = [], []
    for local_id, client, service_id in SELECTION:
        catalog = catalogs[client]
        source = next(service for service in catalog['services'] if service['service_id'] == service_id)
        section = next(section for section in catalog['sections'] if section['section_id'] == source['section_id'])
        direction = next((item for item in directions if item['name'] == section['title']), None)
        if direction is None:
            direction = dict(id=f'direction-{len(directions)}', name=section['title'], subtitle=section['subtitle'])
            directions.append(direction)
        offers = []
        for row in source['price']['rows']:
            group = next((group['title'] for group in source['offer_groups'] if row['offer_id'] in group['offer_ids']), '')
            offers.append(dict(id=row['offer_id'], name=row['variant_label'] or source['name'],
                subtitle=row['scope_text'] or '', group=group, mode=row['mode'],
                price_text='' if row['mode'] == 'no_public_price' else row['price_display_text'],
                client_id=client, detail=source['details'][row['offer_id']]))
        services.append(dict(id=local_id, source_client=client, source_service=service_id,
            direction=direction['id'], name=source['name'], subtitle=source['subtitle'],
            summary_text=source['price_summary_text'] or '', offers=offers))
    content = dict(as_of='2026-10-17', source_versions={client:catalog['catalog_version'] for client,catalog in sorted(catalogs.items())}, directions=directions, services=services)
    serialized = json.dumps(content, ensure_ascii=False, indent=2).replace('<', '\\u003c')
    (HERE / 'reference-data.js').write_text('// Generated by sync-reference.py from canonical demo catalogs.\nwindow.WidgetPlaygroundData = '+serialized+';\n', encoding='utf-8')
    answer = (REPO / 'static/widget/answer_format.js').read_text(encoding='utf-8').replace('export function ', 'function ')
    renderer = (REPO / 'static/widget/price_card.js').read_text(encoding='utf-8').replace('import { setBotAnswerBody } from "./answer_format.js";', '').replace('export function ', 'function ')
    (HERE / 'reference-renderer.js').write_text('// Generated copy of the real answer formatter and price card renderer.\n(() => {\n'+answer+'\n'+renderer+'\nwindow.WidgetPlaygroundRenderer = {renderPriceBody};\n})();\n', encoding='utf-8')
    # Same form markup and field handlers; only loading/delivery are local fixtures.
    booking = (REPO / 'static/widget/booking_form.js').read_text(encoding='utf-8')
    booking = booking.replace("import { visitorIdForClient } from './api.js';", '').replace('export function ', 'function ')
    start = booking.index('  async function load(){')
    end = booking.index('  function renderAll()', start)
    booking = booking[:start] + "  async function load(){definition={checkbox_text:'Даю согласие на обработку имени и телефона для связи по моей заявке.'};}\n" + booking[end:]
    start = booking.index('        body={client_id:')
    end = booking.index('    mount.append(form);', start)
    booking = booking[:start] + """      }
      result={ok:true,message:'Спасибо за обращение! Администратор свяжется с вами и поможет согласовать время.'};
      draft.name='';draft.phone='';draft.wish='';draft.consent=false;draft.selection=null;
      renderAll();
    };
""" + booking[end:]
    with (HERE / 'reference-renderer.js').open('a', encoding='utf-8') as target:
        target.write('\n// Local-only booking fixture; no network transport.\n(() => {\n'+booking+'\nwindow.WidgetPlaygroundRenderer.createBookingForm = createBookingForm;\n})();\n')
    css = (REPO / 'static/widget/widget.css').read_text(encoding='utf-8')
    card_css = css[css.index('.clinic-price-card {'):css.index('.clinic-shell__header-avatar .clinic-shell__avatar-fallback')]
    form_end = css.index('}', css.index('.clinic-booking button:disabled'))+1
    form_css = css[css.index('.clinic-catalog__heading {'):form_end]
    arrow_start = css.index('.clinic-turn__btn--cta-primary::after,')
    arrow_css = css[arrow_start:css.index('}', arrow_start)+1]
    css = card_css + '\n' + form_css + '\n' + arrow_css
    css = re.sub(r'letter-spacing\s*:[^;]+;', '', css)
    css += '\n.clinic-price-card__detail summary>.clinic-price-card__chevron{height:13px;transform:rotate(90deg)}\n.clinic-price-card__detail[open] summary>.clinic-price-card__chevron{transform:rotate(-90deg)}\n@media(max-width:380px){.clinic-booking{padding:12px}}\n'
    (HERE / 'reference-cards.css').write_text('/* Real widget price card styles; tracking removed for this playground. */\n'+css, encoding='utf-8')
    print(f'Exported {len(services)} complete services / {sum(len(service["offers"]) for service in services)} offers from three demo packs.')

if __name__ == '__main__':
    refresh()
